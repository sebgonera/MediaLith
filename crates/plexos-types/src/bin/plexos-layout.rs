//! Emits the canonical partition layout as an `sfdisk` script.
//!
//! `buildroot/README.md` states the rule this binary exists to enforce: no partition
//! GUID, size, or label is ever written by hand in the image tooling. They come from
//! [`plexos_types::partition`], which is the single definition (ADR-0003).
//!
//! Without this, `post-image.sh` would have to repeat the layout in shell, and the
//! first divergence between the two would produce a disk that `plexos-init` cannot
//! reason about — the exact failure the single-definition rule prevents.
//!
//! Two output formats, because two tools are in play. `sgdisk` is what
//! `post-image.sh` drives, since `BR2_PACKAGE_HOST_GPTFDISK` puts it in `$HOST_DIR`
//! and a Buildroot-supplied tool is pinned with the rest of the build. `sfdisk` is
//! kept for inspection and round-tripping, and is the format a human reads.
//!
//! ```text
//! plexos-layout                     # sfdisk script on stdout
//! plexos-layout --format sgdisk     # sgdisk arguments, one token per line
//! ```

use std::process::ExitCode;

use plexos_types::partition::{LAYOUT_X86_64, PartitionSpec};

/// Bytes per sector. GPT tooling works in 512-byte sectors regardless of the
/// physical sector size of the target disk.
const SECTOR_BYTES: u64 = 512;

/// Where the first partition starts. 1 MiB is the universal alignment convention;
/// starting earlier misaligns every partition on a 4K-native disk.
const FIRST_LBA: u64 = 2048;

fn sectors_from_mib(mib: u64) -> u64 {
    mib * 1024 * 1024 / SECTOR_BYTES
}

/// Renders one partition as an `sfdisk` script line.
///
/// A partition with no size takes the remainder of the disk, which `sfdisk` expresses
/// by omitting the `size=` field entirely.
fn render_line(spec: &PartitionSpec) -> String {
    let type_guid = spec.type_guid.to_uppercase();
    match spec.size_mib {
        Some(mib) => format!(
            "size={}, type={}, name=\"{}\"",
            sectors_from_mib(mib),
            type_guid,
            spec.label
        ),
        None => format!("type={}, name=\"{}\"", type_guid, spec.label),
    }
}

fn render() -> String {
    let mut out = format!(
        "# Generated by plexos-layout from plexos_types::partition::LAYOUT_X86_64.\n\
         # Do not edit: edit the Rust definition, which is the contract (ADR-0003).\n\
         label: gpt\n\
         unit: sectors\n\
         first-lba: {FIRST_LBA}\n\n"
    );
    for spec in &LAYOUT_X86_64 {
        out.push_str(&render_line(spec));
        out.push('\n');
    }
    out
}

/// Renders the layout as `sgdisk` arguments, one token per line.
///
/// One token per line rather than a single quoted string so that a caller can read
/// them into a shell array with `mapfile` and pass them through unmangled — a label
/// or GUID never has to survive a round trip through word splitting.
///
/// Partitions are numbered from 1 in layout order, and every start is given as `0`,
/// meaning "the next aligned free sector". `sgdisk` aligns to 2048 sectors by
/// default, which matches the 1 MiB convention the sfdisk output states explicitly.
fn render_sgdisk() -> String {
    let mut out = String::new();
    for (index, spec) in LAYOUT_X86_64.iter().enumerate() {
        let number = index + 1;
        // End sector 0 means "use the rest of the disk", which is exactly the
        // meaning of a `None` size in the contract.
        let end = match spec.size_mib {
            Some(mib) => format!("+{mib}M"),
            None => "0".to_owned(),
        };
        for token in [
            "-n".to_owned(),
            format!("{number}:0:{end}"),
            "-t".to_owned(),
            format!("{number}:{}", spec.type_guid.to_uppercase()),
            "-c".to_owned(),
            format!("{number}:{}", spec.label),
        ] {
            out.push_str(&token);
            out.push('\n');
        }
    }
    out
}

const USAGE: &str = "\
plexos-layout — emit the MediaLith partition layout (ADR-0003)

USAGE:
    plexos-layout [--format sfdisk|sgdisk]

FORMATS:
    sfdisk   (default) a script for `sfdisk disk.img < layout.sfdisk`
    sgdisk   arguments, one token per line, for `sgdisk \"${ARGS[@]}\" disk.img`
";

fn main() -> ExitCode {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let mut format = "sfdisk".to_owned();

    let mut tokens = args.iter();
    while let Some(token) = tokens.next() {
        match token.as_str() {
            "--help" | "-h" => {
                print!("{USAGE}");
                return ExitCode::SUCCESS;
            }
            "--format" => {
                let Some(value) = tokens.next() else {
                    eprintln!("plexos-layout: --format needs a value");
                    return ExitCode::from(64); // EX_USAGE
                };
                value.clone_into(&mut format);
            }
            other => {
                eprintln!("plexos-layout: unrecognised argument {other:?}\n");
                eprint!("{USAGE}");
                return ExitCode::from(64);
            }
        }
    }

    match format.as_str() {
        "sfdisk" => print!("{}", render()),
        "sgdisk" => print!("{}", render_sgdisk()),
        other => {
            eprintln!("plexos-layout: unknown format {other:?}; expected sfdisk or sgdisk");
            return ExitCode::from(64);
        }
    }
    ExitCode::SUCCESS
}

#[cfg(test)]
mod tests {
    use super::*;
    use plexos_types::Slot;
    use plexos_types::partition::{GUID_ESP, LABEL_VAR};

    #[test]
    fn every_partition_in_the_contract_appears_exactly_once() {
        let script = render();
        for spec in &LAYOUT_X86_64 {
            let needle = format!("name=\"{}\"", spec.label);
            assert_eq!(
                script.matches(&needle).count(),
                1,
                "{} should appear exactly once in:\n{script}",
                spec.label
            );
        }
    }

    #[test]
    fn only_the_final_partition_omits_a_size() {
        let script = render();
        let lines: Vec<&str> = script
            .lines()
            .filter(|l| l.starts_with("size=") || l.starts_with("type="))
            .collect();
        assert_eq!(lines.len(), LAYOUT_X86_64.len());

        let (last, rest) = lines.split_last().unwrap();
        assert!(
            last.starts_with("type="),
            "/var must take the remainder: {last}"
        );
        assert!(
            rest.iter().all(|l| l.starts_with("size=")),
            "only the last partition may be unsized"
        );
    }

    #[test]
    fn sizes_are_converted_to_sectors_not_copied_as_mebibytes() {
        // A 512 MiB ESP is 1048576 sectors. Emitting "512" here would silently
        // produce a 256 KiB ESP, which is the kind of error that only shows up as an
        // unbootable disk.
        let script = render();
        assert!(
            script.contains("size=1048576,"),
            "ESP size not in sectors:\n{script}"
        );
    }

    #[test]
    fn guids_are_uppercase_for_sfdisk() {
        // sfdisk accepts either case, but writes uppercase; matching it keeps a
        // round-trip through `sfdisk --dump` textually identical.
        let script = render();
        assert!(script.contains(&GUID_ESP.to_uppercase()), "{script}");
        assert!(
            !script.contains(GUID_ESP),
            "lowercase GUID leaked into the script:\n{script}"
        );
    }

    #[test]
    fn the_script_is_a_valid_gpt_header() {
        let script = render();
        assert!(script.starts_with("# Generated by plexos-layout"));
        assert!(script.contains("\nlabel: gpt\n"));
        assert!(script.contains("\nunit: sectors\n"));
        assert!(script.contains("\nfirst-lba: 2048\n"));
    }

    #[test]
    fn sgdisk_form_describes_the_same_layout_as_the_sfdisk_form() {
        let script = render_sgdisk();
        let tokens: Vec<&str> = script.lines().collect();
        assert_eq!(
            tokens.len(),
            LAYOUT_X86_64.len() * 6,
            "expected -n/-t/-c and a value for each partition"
        );
        for (index, spec) in LAYOUT_X86_64.iter().enumerate() {
            let number = index + 1;
            let base = index * 6;
            assert_eq!(tokens[base], "-n");
            assert_eq!(tokens[base + 2], "-t");
            assert_eq!(
                tokens[base + 3],
                format!("{number}:{}", spec.type_guid.to_uppercase())
            );
            assert_eq!(tokens[base + 4], "-c");
            assert_eq!(tokens[base + 5], format!("{number}:{}", spec.label));
        }
    }

    #[test]
    fn only_the_final_sgdisk_partition_consumes_the_remainder() {
        let script = render_sgdisk();
        let tokens: Vec<&str> = script.lines().collect();
        let ranges: Vec<&str> = tokens
            .iter()
            .enumerate()
            .filter(|(i, _)| i % 6 == 1)
            .map(|(_, t)| *t)
            .collect();
        let (last, rest) = ranges.split_last().unwrap();
        assert!(last.ends_with(":0:0"), "/var must take the rest: {last}");
        assert!(
            rest.iter().all(|r| r.contains(":0:+")),
            "every other partition must be explicitly sized: {rest:?}"
        );
    }

    #[test]
    fn sgdisk_tokens_never_need_shell_quoting() {
        // The caller reads these with mapfile and expands them as an array. A token
        // containing whitespace would silently split into two arguments.
        for token in render_sgdisk().lines() {
            assert!(!token.is_empty(), "empty token in sgdisk output");
            assert!(
                !token.chars().any(char::is_whitespace),
                "token {token:?} would not survive array expansion"
            );
        }
    }

    #[test]
    fn both_slots_and_var_are_present() {
        let script = render();
        for slot in Slot::ALL {
            assert!(script.contains(slot.usr_label()), "{script}");
            assert!(script.contains(slot.verity_label()), "{script}");
        }
        assert!(script.contains(LABEL_VAR));
    }
}
